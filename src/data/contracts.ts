/**
 * EVOS data contracts.
 * Canonical entity shapes shared by the UI, services and future backend (e.g. Supabase).
 * Units are fixed per field: power kW, energy kWh, SoC/SoH in percent (0–100, never fractions),
 * currency INR, carbon intensity gCO2e/kWh, timestamps ISO-8601 with explicit timezone.
 */

/** How a value came to exist. Shown to users as a provenance badge. */
export type Provenance =
  | "real" // measured / real data from a connected source
  | "imported" // loaded from an imported dataset file
  | "calculated" // deterministically derived from other values
  | "calibrated" // simulation calibrated against a real dataset
  | "simulated" // generated by the EVOS demo model
  | "forecast" // predicted value
  | "demo" // illustrative preview, not a model output
  | "not-connected";

export const PROVENANCE_LABEL: Record<Provenance, string> = {
  real: "Real data",
  imported: "Imported data",
  calculated: "Calculated",
  calibrated: "Calibrated simulation",
  simulated: "Simulated",
  forecast: "Forecast",
  demo: "Demo preview",
  "not-connected": "Not connected",
};

export interface SourceRef {
  datasetId: string;
  provenance: Provenance;
  period?: { from: string; to: string };
  importedAt?: string;
  processing?: string[];
  limitations?: string[];
}

export type FieldType = "string" | "number" | "integer" | "boolean" | "timestamp" | "enum";
export interface FieldSpec {
  name: string;
  type: FieldType;
  unit?: string;
  required: boolean;
  kind: "measured" | "derived" | "simulated" | "predicted" | "config" | "identifier";
  rule?: string;
  ref?: string; // relationship: entity.field
}

export interface EntitySpec {
  id: string;
  name: string;
  description: string;
  classification: Provenance;
  fields: FieldSpec[];
}

// ---- Entity types used by the application ----
export type VehicleClass = "Shuttle bus" | "Utility cart" | "Service van";
export interface Vehicle {
  id: string;
  vehicleClass: VehicleClass;
  batteryCapacityKWh: number;
  maxChargePowerKW: number;
  socPct: number;
  targetSocPct: number;
  arrivalAt: string;
  departureAt: string;
  priority: "High" | "Normal" | "Low";
  source: SourceRef;
}
export interface Charger {
  id: string;
  type: "AC" | "DC";
  ratedPowerKW: number;
  connector: string;
  status: "Available" | "Charging" | "Fault" | "Derated";
  source: SourceRef;
}
export interface ChargingSession {
  sessionId: string;
  chargerId: string;
  vehicleId?: string;
  connectionAt: string;
  disconnectionAt: string;
  energyDeliveredKWh: number;
  powerKW: number;
  source: SourceRef;
}
export interface BatteryMeasurement {
  batteryId: string;
  cycle: number;
  voltageV?: number;
  currentA?: number;
  temperatureC?: number;
  capacityAh?: number;
  referenceCapacityAh?: number;
  sohPct?: number;
  testAt: string;
  source: SourceRef;
}
export interface TimeSeriesPoint {
  at: string;
  value: number | null; // null = missing, never silently zero-filled
  unit: string;
  lower?: number;
  upper?: number;
}
export interface SimulationRunRecord {
  id: string;
  configId: string;
  strategy: string;
  status: "configured" | "running" | "completed" | "failed" | "demo-preview";
  startedAt?: string;
  endedAt?: string;
  algorithmVersion: string;
  datasetVersions: Record<string, string>;
  metrics?: Record<string, number>;
  error?: string;
}
export interface DecisionRecord {
  decisionId: string;
  at: string;
  selectedAction: string;
  reason: string;
  inputs: Record<string, string | number>;
  constraints: string[];
  alternatives: string[];
  costImpactINR?: number;
  carbonImpactKg?: number;
  wearImpactINR?: number;
  deadlineRisk: "None" | "At risk";
  fallback?: string;
  override?: string;
  algorithmVersion: string;
  dataSources: string[];
}

/** Async state every data-driven view handles. */
export type LoadState<T> =
  | { status: "loading" }
  | { status: "error"; error: string; retry?: () => void }
  | { status: "not-connected"; message: string }
  | { status: "empty" }
  | { status: "ready"; data: T; partial?: string; stale?: string };
